/**
 * Library bootstrap — loads the seeded Library from bundled assets on first
 * launch (empty database). On subsequent launches this is a no-op.
 *
 * The actual asset files are produced by the Python build pipeline
 * (build/01–06_*.py) and copied into assets/seeded_library/ during the build
 * step.  This module reads them, inserts rows into `books` and `passages`,
 * and writes cross-references.
 *
 * (design spec §3.5, Task 1.5)
 */

import * as FileSystem from 'expo-file-system/legacy';

import type { SQLiteDatabase } from 'expo-sqlite';

import bibleWebSeed from '../../assets/seeded_library/bible_web.json';
import bibleKjvSeed from '../../assets/seeded_library/bible_kjv.json';

/** The seeded-library asset directory. */
const ASSET_DIR = `${FileSystem.documentDirectory}seeded_library`;

/** Files we expect to find in the bundled assets. */
const LIBRARY_FILES = {
  biblePassages: 'bible_passages.json',
  bibleBooks: 'bible_books.json',
  voicePassages: 'voice_passages.json',
  voiceBooks: 'voice_books.json',
  crossRefs: 'cross_references.json',
  verseOfDay: 'verse_of_day.json',
  manifest: 'library_manifest.json',
} as const;

interface BiblePassageRow {
  id: number;
  book: string;
  chapter: number;
  verse_start: number;
  verse_end: number;
  text: string;
  translation: string;
  chunk_id: number;
}

interface VoicePassageRow {
  id: number;
  book_id: string;
  author: string;
  work: string;
  text: string;
  chunk_id: number;
}

interface BookRow {
  id: string;
  title: string;
  author?: string;
  era?: string;
  package_id: string;
  type: string;
  translation?: string;
  source?: string;
  order?: number;
  testament?: string;
  passage_count?: number;
}

interface CrossRefRow {
  from_ref: string;
  to_ref: string;
}

interface LibraryManifest {
  version: number;
  bible_translations: string[];
  voice_works: number;
  vector_models: string[];
}

async function loadJsonAsset<T>(filename: string): Promise<T | null> {
  try {
    // In a bare workflow project, assets can be loaded via expo-asset.
    // For now we attempt to read from the document directory (post-copy)
    // and fall back gracefully if the file is missing — the app still works
    // with an empty library; the user just gets no resonance until packages
    // are loaded.
    const path = `${ASSET_DIR}/${filename}`;
    const info = await FileSystem.getInfoAsync(path);
    if (!info.exists) {
      return null;
    }
    const content = await FileSystem.readAsStringAsync(path);
    return JSON.parse(content) as T;
  } catch {
    return null;
  }
}

// ── Bundled Scripture (issue #53, P1-14) ────────────────────────────────────
//
// Scripture ships inside the app bundle as compact tuple-format JSON
// (generated by scripts/library/build_mobile_scripture.py from the
// public-domain corpus modules): { translation, books[], verses:
// [bookIndex, chapter, verse, text][] }. WEB is the default translation,
// KJV is bundled alongside. This replaces the old expectation that a
// post-copy step would place files in the document directory — no such
// step ever existed, so first launch always booted into an empty DB.

interface ScriptureSeed {
  translation: string;
  books: string[];
  verses: [number, number, number, string][];
}

const SCRIPTURE_SEEDS: ScriptureSeed[] = [
  bibleWebSeed as ScriptureSeed,
  bibleKjvSeed as ScriptureSeed,
];

function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

/** Seeds books + passages from the bundled Scripture files, once. */
async function seedBundledScripture(db: SQLiteDatabase): Promise<void> {
  const existing = await db.getFirstAsync<{ c: number }>(
    `SELECT COUNT(*) as c FROM passages WHERE translation IS NOT NULL;`
  );
  if (existing && existing.c > 0) {
    return; // Already seeded
  }

  let nextId = 1;
  for (const seed of SCRIPTURE_SEEDS) {
    const bookIds = seed.books.map(
      (name) => `${seed.translation}_${name.replace(/\s+/g, '_')}`
    );
    for (let i = 0; i < seed.books.length; i++) {
      await db.runAsync(
        `INSERT OR IGNORE INTO books (id, title, author, era, package_id, type, translation, source)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?);`,
        bookIds[i],
        seed.books[i],
        null,
        null,
        'seeded',
        'bible',
        seed.translation,
        'bundled'
      );
    }

    // Batched multi-row inserts — 31k verses per translation would be
    // far too slow one runAsync at a time on a phone.
    const BATCH = 400;
    await db.withTransactionAsync(async () => {
      for (let start = 0; start < seed.verses.length; start += BATCH) {
        const rows = seed.verses.slice(start, start + BATCH);
        const values = rows
          .map(([bookIdx, chapter, verse, text]) => {
            const id = nextId++;
            return (
              `(${id}, ${sqlString(bookIds[bookIdx])}, ${chapter}, ` +
              `${verse}, ${verse}, ${sqlString(text)}, ` +
              `${sqlString(seed.translation)}, ${id})`
            );
          })
          .join(', ');
        await db.execAsync(
          `INSERT OR REPLACE INTO passages (id, book_id, chapter, verse_start, verse_end, text, translation, chunk_id) VALUES ${values};`
        );
      }
    });
    // eslint-disable-next-line no-console
    console.log(
      `[library] seeded ${seed.translation} — ${seed.verses.length} verses`
    );
  }
}

/**
 * Reads the seeded library assets and populates the database.  Called on
 * every launch but returns immediately when the library is already present.
 */
export async function libraryBootstrap(db: SQLiteDatabase): Promise<void> {
  // Bundled Scripture first (P1-14) — idempotent, no-ops once seeded.
  await seedBundledScripture(db);

  // Check if books already exist
  const count = await db.getFirstAsync<{ c: number }>(
    `SELECT COUNT(*) as c FROM books;`
  );
  if (count && count.c > 0) {
    return; // Already populated
  }

  const manifest = await loadJsonAsset<LibraryManifest>(LIBRARY_FILES.manifest);
  // eslint-disable-next-line no-console
  console.log('[library] bootstrapping seeded library...', manifest?.version ?? 'unknown');

  // ── Bible books ──────────────────────────────────────────────────────
  const bibleBooks = await loadJsonAsset<BookRow[]>(LIBRARY_FILES.bibleBooks);
  if (bibleBooks) {
    for (const b of bibleBooks) {
      await db.runAsync(
        `INSERT OR IGNORE INTO books (id, title, author, era, package_id, type, translation, source)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?);`,
        b.id,
        b.title,
        b.author ?? null,
        b.era ?? null,
        b.package_id ?? 'seeded',
        b.type,
        b.translation ?? null,
        b.source ?? null
      );
    }
  }

  // ── Bible passages (batch insert) ───────────────────────────────────
  const biblePassages = await loadJsonAsset<BiblePassageRow[]>(LIBRARY_FILES.biblePassages);
  if (biblePassages) {
    await db.withTransactionAsync(async () => {
      for (const p of biblePassages) {
        // Build book_id from translation + book name order
        const bookId = `${p.translation}_${p.book.replace(/\s+/g, '_')}`;
        await db.runAsync(
          `INSERT OR REPLACE INTO passages (id, book_id, chapter, verse_start, verse_end, text, translation, chunk_id)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?);`,
          p.id,
          bookId,
          p.chapter,
          p.verse_start,
          p.verse_end,
          p.text,
          p.translation,
          p.chunk_id
        );
      }
    });
  }

  // ── Voice books ─────────────────────────────────────────────────────
  const voiceBooks = await loadJsonAsset<BookRow[]>(LIBRARY_FILES.voiceBooks);
  if (voiceBooks) {
    for (const b of voiceBooks) {
      await db.runAsync(
        `INSERT OR IGNORE INTO books (id, title, author, era, package_id, type, translation, source)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?);`,
        b.id,
        b.title,
        b.author ?? null,
        b.era ?? null,
        b.package_id ?? 'seeded',
        b.type,
        b.translation ?? null,
        b.source ?? null
      );
    }
  }

  // ── Voice passages ──────────────────────────────────────────────────
  const voicePassages = await loadJsonAsset<VoicePassageRow[]>(LIBRARY_FILES.voicePassages);
  if (voicePassages) {
    await db.withTransactionAsync(async () => {
      for (const p of voicePassages) {
        await db.runAsync(
          `INSERT OR REPLACE INTO passages (id, book_id, chapter, verse_start, verse_end, text, translation, chunk_id)
           VALUES (?, ?, NULL, NULL, NULL, ?, NULL, ?);`,
          p.id,
          p.book_id,
          p.text,
          p.chunk_id
        );
      }
    });
  }

  // ── Cross-references ───────────────────────────────────────────────
  // Stored as a JSON array under app_settings('cross_references') so the
  // Word tab can resolve marginal cross-ref links per verse_ref. A count is
  // also kept for diagnostics. A dedicated table may be added in a future
  // migration if lookup queries need indexing.
  const crossRefs = await loadJsonAsset<CrossRefRow[]>(LIBRARY_FILES.crossRefs);
  if (crossRefs) {
    await db.runAsync(
      `INSERT OR REPLACE INTO app_settings (key, value) VALUES (?, ?);`,
      'cross_references',
      JSON.stringify(crossRefs)
    );
    await db.runAsync(
      `INSERT OR REPLACE INTO app_settings (key, value) VALUES (?, ?);`,
      'cross_references_count',
      String(crossRefs.length)
    );
  }

  // ── Verse of the day ────────────────────────────────────────────────
  const verseOfDay = await loadJsonAsset<unknown[]>(LIBRARY_FILES.verseOfDay);
  if (verseOfDay) {
    await db.runAsync(
      `INSERT OR REPLACE INTO app_settings (key, value) VALUES (?, ?);`,
      'verse_of_day_count',
      String(verseOfDay.length)
    );
  }

  // ── Record library version ─────────────────────────────────────────
  await db.runAsync(
    `INSERT OR REPLACE INTO app_settings (key, value) VALUES (?, ?);`,
    'library_version',
    String(manifest?.version ?? 1)
  );

  const finalCount = await db.getFirstAsync<{ c: number }>(
    `SELECT COUNT(*) as c FROM books;`
  );
  // eslint-disable-next-line no-console
  console.log(`[library] bootstrap complete — ${finalCount?.c ?? 0} books`);
}
